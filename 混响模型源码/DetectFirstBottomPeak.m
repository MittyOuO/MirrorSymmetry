function [peakIndex, Info] = DetectFirstBottomPeak(RL, timeAxis, varargin)
%DETECTFIRSTBOTTOMPEAK 独立检测直达峰后的第一个强海底反射峰。
% 该函数把直达事件视为第一个主事件，并在保护时间之后寻找第二个主事件。
% 为避免把直达尾迹或弱小多途误认为B1，候选峰除满足绝对显著度外，还必须
% 位于直达峰以下 RelativeHeightDropDB 指定的动态范围内。

p=inputParser;
addParameter(p,'SmoothWindowSec',0.05,@(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x>0);
addParameter(p,'DirectGuardSec',1.2,@(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x>=0);
addParameter(p,'PeakProminenceDB',6,@(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x>0);
addParameter(p,'NoiseMarginDB',6,@(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x>0);
addParameter(p,'RelativeHeightDropDB',30,@(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x>0);
addParameter(p,'MinPeakDistanceSec',0.5,@(x)isnumeric(x)&&isscalar(x)&&isfinite(x)&&x>0);
parse(p,varargin{:});

RL=real(double(RL(:)));
timeAxis=double(timeAxis(:));
N=min(numel(RL),numel(timeAxis));
RL=RL(1:N); timeAxis=timeAxis(1:N);
assert(N>=10 && all(isfinite(timeAxis)) && all(diff(timeAxis)>0), ...
    'DetectFirstBottomPeak:InvalidInput','RL与timeAxis必须包含至少10个递增时刻样本。');
finiteMask=isfinite(RL);
assert(any(finiteMask),'DetectFirstBottomPeak:NoFiniteRL','RL中没有有限样本。');

dt=median(diff(timeAxis));
smoothPoints=max(3,round(p.Results.SmoothWindowSec/dt));
rlSmooth=movmean(RL,smoothPoints,'omitnan');
rlSmooth(~isfinite(rlSmooth))=-Inf;

[directPeakValue,directIndex]=max(rlSmooth);
directTime=timeAxis(directIndex);
searchStartIndex=find(timeAxis>=directTime+p.Results.DirectGuardSec,1,'first');
assert(~isempty(searchStartIndex) && searchStartIndex<N, ...
    'DetectFirstBottomPeak:SearchWindowEmpty','直达峰后的B1搜索区为空。');

finiteValues=sort(rlSmooth(isfinite(rlSmooth)));
lowCount=max(1,round(0.20*numel(finiteValues)));
noiseFloor=median(finiteValues(1:lowCount),'omitnan');
strictHeight=max(noiseFloor+p.Results.NoiseMarginDB, ...
    directPeakValue-p.Results.RelativeHeightDropDB);

searchRL=rlSmooth(searchStartIndex:end);
searchTime=timeAxis(searchStartIndex:end);
[peakValues,peakTimes]=findpeaks(searchRL,searchTime, ...
    'MinPeakProminence',p.Results.PeakProminenceDB, ...
    'MinPeakHeight',strictHeight, ...
    'MinPeakDistance',p.Results.MinPeakDistanceSec);
method='strict_second_major_peak';
usedHeight=strictHeight;
usedProminence=p.Results.PeakProminenceDB;

if isempty(peakTimes)
    usedHeight=max(noiseFloor+max(3,p.Results.NoiseMarginDB/2), ...
        directPeakValue-(p.Results.RelativeHeightDropDB+10));
    usedProminence=max(3,p.Results.PeakProminenceDB/2);
    [peakValues,peakTimes]=findpeaks(searchRL,searchTime, ...
        'MinPeakProminence',usedProminence, ...
        'MinPeakHeight',usedHeight, ...
        'MinPeakDistance',p.Results.MinPeakDistanceSec);
    method='relaxed_second_major_peak';
end

assert(~isempty(peakTimes),'DetectFirstBottomPeak:PeakNotFound', ...
    ['未检测到直达峰后的第一海底反射主峰。请检查信号、保护时间或峰值门限；' ...
     '程序不会退化为任意相关性对齐。']);

firstBottomPeakTime=peakTimes(1);
firstBottomPeakValue=peakValues(1);
[~,peakIndex]=min(abs(timeAxis-firstBottomPeakTime));

Info=struct( ...
    'Method',method, ...
    'Reference','second peak / first bottom reflection peak', ...
    'DirectIndex',directIndex, ...
    'DirectTimeSec',directTime, ...
    'DirectPeakValueDB',directPeakValue, ...
    'SearchStartIndex',searchStartIndex, ...
    'SearchStartTimeSec',timeAxis(searchStartIndex), ...
    'FirstBottomPeakIndex',peakIndex, ...
    'FirstBottomPeakTimeSec',timeAxis(peakIndex), ...
    'FirstBottomPeakValueDB',firstBottomPeakValue, ...
    'NoiseFloorDB',noiseFloor, ...
    'MinPeakHeightDB',usedHeight, ...
    'MinPeakProminenceDB',usedProminence, ...
    'SmoothWindowSec',p.Results.SmoothWindowSec, ...
    'DirectGuardSec',p.Results.DirectGuardSec, ...
    'RelativeHeightDropDB',p.Results.RelativeHeightDropDB, ...
    'MinPeakDistanceSec',p.Results.MinPeakDistanceSec);
end
