function Params = GetDefaultBTRPeakValidationParams()
%GetDefaultBTRPeakValidationParams Formal shared BTR validation authority.
Params=struct();
Params.PassThresholdSec=0.500;
Params.Peak=struct('InputScale','dB','ThresholdMode','relative', ...
    'RelativeThresholdDB',-35,'SmoothTime',0.08, ...
    'MinPeakProminenceDB',4,'MinPeakDistanceSec',0.35, ...
    'MaxNumPeaksPerBeam',8,'Verbose',false);
Params.Match=struct('TauInterval',0.35,'MaxAbsTimeDiff',2.0, ...
    'PassThreshold',Params.PassThresholdSec,'BeamAngleTolerance',1e-6, ...
    'AllowSinglePeakMatch',false,'Verbose',false);
end
