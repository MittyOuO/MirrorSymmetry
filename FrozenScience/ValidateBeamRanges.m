function ValidateBeamRanges(MainBeam, SideRange)
%ValidateBeamRanges Validate physical ordering without silently sorting.
MainBeam = double(MainBeam(:).');
SideRange = double(SideRange);
if numel(MainBeam) ~= 2 || ~isequal(size(SideRange), [2 2]) || ...
        any(~isfinite(MainBeam)) || any(~isfinite(SideRange(:)))
    error('ValidateBeamRanges:InvalidShape', ...
        'MainBeam must be 1x2 and SideRange must be 2x2 finite numeric arrays.');
end

constraints = [ ...
    SideRange(1,1) <= SideRange(1,2), ...
    SideRange(1,2) <= MainBeam(2), ...
    MainBeam(2) <= MainBeam(1), ...
    MainBeam(1) <= SideRange(2,1), ...
    SideRange(2,1) <= SideRange(2,2)];
labels = { ...
    'SideRange(1,1) <= SideRange(1,2)', ...
    'SideRange(1,2) <= MainBeam(2)', ...
    'MainBeam(2) <= MainBeam(1)', ...
    'MainBeam(1) <= SideRange(2,1)', ...
    'SideRange(2,1) <= SideRange(2,2)'};
if ~all(constraints)
    failed = strjoin(labels(~constraints), '; ');
    error('ValidateBeamRanges:InvalidOrdering', ...
        'Invalid beam ordering. MainBeam=%s, SideRange=%s. Violated: %s', ...
        mat2str(MainBeam), mat2str(SideRange), failed);
end
end
