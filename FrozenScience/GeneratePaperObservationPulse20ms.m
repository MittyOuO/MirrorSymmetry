function [pulse,t,meta] = GeneratePaperObservationPulse20ms(fs)
%GeneratePaperObservationPulse20ms Frozen paper-observation pulse shape.
% This is a sampled representation of one continuous parameter set.  It is
% not a measured explosion waveform and carries no model-specific gain.
arguments
    fs (1,1) double {mustBeFinite,mustBePositive}
end
f0=1000; bandwidth=1000; duration=.020; tau=.002;
t=(0:1/fs:duration).';
ideal=exp(-t/tau);
fLow=f0-bandwidth/2; fHigh=f0+bandwidth/2;
assert(fHigh<fs/2,'P20:SamplingRateTooLow');
[z,p,k]=butter(4,[fLow fHigh]/(fs/2));
[sos,g]=zp2sos(z,p,k);
pulse=g*sosfilt(sos,ideal);
shapePeak=max(abs(pulse));
assert(isfinite(shapePeak)&&shapePeak>0,'P20:InvalidPulseNormalization');
pulse=pulse/shapePeak;
meta=struct( ...
    'ContractVersion','P20_PAPER_OBSERVER_v1', ...
    'ScientificIdentity','center-frequency-equivalent finite-time observation/source-reference operator', ...
    'MeasuredExplosionWaveform',false, ...
    'FullBroadbandPropagationModel',false, ...
    'F0Hz',f0,'BandwidthHz',bandwidth,'FLowHz',fLow,'FHighHz',fHigh, ...
    'DurationS',duration,'ShockDecayTauS',tau,'FilterFamily','Butterworth', ...
    'FilterOrder',4,'FilterApplication','causal_ZPK_to_SOS_sosfilt_once', ...
    'ShapeNormalization','unit_discrete_peak', ...
    'MeasurementSourceAmplitudeCalibration','UNRESOLVED_NOT_APPLIED', ...
    'AbsoluteRLAccuracyClaim','NOT_AUTHORIZED', ...
    'FsHz',fs,'SampleCount',numel(pulse), ...
    'PhysicalShapeEnergy',sum(abs(pulse).^2,'double')/fs);
end
