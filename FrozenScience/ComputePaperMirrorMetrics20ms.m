function M = ComputePaperMirrorMetrics20ms(zPlus,zMinus,hPlus,hMinus,fs)
%ComputePaperMirrorMetrics20ms Complete metric-authority side quantities.
arguments
    zPlus {mustBeNumeric}
    zMinus {mustBeNumeric}
    hPlus {mustBeNumeric}
    hMinus {mustBeNumeric}
    fs (1,1) double {mustBeFinite,mustBePositive}
end
assert(numel(zPlus)==numel(zMinus)&&numel(hPlus)==numel(hMinus),'P20:MirrorLengthMismatch');
deltaH=norm(hPlus(:)-hMinus(:))/max(norm(hPlus(:))+norm(hMinus(:)),realmin('double'));
deltaZ=norm(zPlus(:)-zMinus(:))/max(norm(zPlus(:))+norm(zMinus(:)),realmin('double'));
t=(0:numel(zPlus)-1)'/fs;q=t>=0&t<60;zp=zPlus(q);zm=zMinus(q);
ep=sum(abs(zp).^2,'double')/fs;em=sum(abs(zm).^2,'double')/fs;den=max(ep+em,realmin('double'));
M=struct( ...
    'MetricRegistryVersion','P20_MIRROR_METRICS_v1', ...
    'DeltaSideH',deltaH, ...
    'DeltaSideHAuthority','L2 distance / sum of two side L2 norms / all stored raw samples / full stored raw support / P20_MIRROR_METRICS_v1', ...
    'DeltaSideZ20',deltaZ, ...
    'DeltaSideZ20Authority','L2 distance / sum of two side L2 norms / all stored observed samples / full stored observed support / P20_MIRROR_METRICS_v1', ...
    'A_E',(ep-em)/den, ...
    'A_E_Authority','signed energy difference / sum of side energies / all samples / Wformal=[0,60s) / P20_MIRROR_METRICS_v1', ...
    'D_pm',sum(abs(zp-zm).^2,'double')/fs/den, ...
    'D_pm_Authority','difference energy / sum of side energies / all samples / Wformal=[0,60s) / P20_MIRROR_METRICS_v1', ...
    'C_pm',abs(sum(zp.*conj(zm),'double')/fs)/max(sqrt(ep*em),realmin('double')), ...
    'C_pm_Authority','absolute complex inner product / geometric mean side energy / all samples / Wformal=[0,60s) / P20_MIRROR_METRICS_v1', ...
    'EPlus',ep,'EMinus',em,'RawSampleCount',numel(hPlus), ...
    'ObservedSampleCount',numel(zPlus),'FormalWindowStartS',0, ...
    'FormalWindowEndExclusiveS',60,'AbsoluteRLAccuracyClaim','NOT_AUTHORIZED');
end
