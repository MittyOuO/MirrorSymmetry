function Receipt=ValidateCompactRecoveryInputs_v1(Context)
%ValidateCompactRecoveryInputs_v1 Fail-closed immutable recovery preflight.
% This validates durable pre-existing authority only. It neither acquires a
% lock nor enters deterministic recovery processing.
arguments
    Context (1,1) struct
end
required={'ScientificRunId','RosterIndex','Seed','SeedPayloadSHA256', ...
    'RandomModelVersion','SourceEventFactsPath','SourceEventFactsSHA256', ...
    'SourceEventFactsBytes','RawCaptureManifestPath','RawCaptureManifestSHA256', ...
    'RawCaptureJournalPath','RawCaptureJournalSHA256','DSALPath','DSALSHA256'};
for k=1:numel(required)
    assert(isfield(Context,required{k}),'G4CRPreflight:MissingField', ...
        'Missing recovery context field %s.',required{k});
end
assert(string(Context.ScientificRunId)=="43b3b9d6-cb24-4ede-9bee-f53e47b505c4", ...
    'G4CRPreflight:ScientificRunId','ScientificRunId is not the original Seed-1 run.');
assert(Context.RosterIndex==1&&Context.Seed==262709171, ...
    'G4CRPreflight:SeedIdentity','Only exact roster index 1 / seed 262709171 is valid.');
assert(string(Context.SeedPayloadSHA256)=="0fa89fb3cc739f4769765d94af6601b7349bb0247874fcedc708ee117a56bd94"&& ...
    Context.RandomModelVersion==1,'G4CRPreflight:RandomIdentity','Payload SHA or RMV changed.');
assert(string(Context.SourceEventFactsSHA256)=="e580ffb394b60fa983a4ec27f0d05645b77dc7691a938b8e52309a8515b98494"&& ...
    Context.SourceEventFactsBytes==112111406979,'G4CRPreflight:SourceEventFactsAuthority', ...
    'SourceEventFacts SHA or bytes changed.');
f=dir(Context.SourceEventFactsPath);assert(~isempty(f)&&f.bytes==Context.SourceEventFactsBytes, ...
    'G4CRPreflight:SourceEventFactsAuthority','SourceEventFacts path or bytes changed.');

assert(isfile(Context.RawCaptureManifestPath)&&hashLocal(Context.RawCaptureManifestPath)==string(Context.RawCaptureManifestSHA256), ...
    'G4CRPreflight:RawCaptureManifest','Raw capture manifest is missing or SHA-mismatched.');
manifest=jsondecode(fileread(Context.RawCaptureManifestPath));
assert(string(manifest.Stage)=="RAW_CAPTURE_COMMITTED"&& ...
    string(manifest.Identity.ScientificRunId)==string(Context.ScientificRunId)&& ...
    string(manifest.SourceEventFactsSHA256)==string(Context.SourceEventFactsSHA256), ...
    'G4CRPreflight:RawCaptureManifest','Raw capture manifest identity/stage changed.');

assert(isfile(Context.RawCaptureJournalPath)&&hashLocal(Context.RawCaptureJournalPath)==string(Context.RawCaptureJournalSHA256), ...
    'G4CRPreflight:RawCaptureJournal','RAW_CAPTURE_COMMITTED journal is missing or SHA-mismatched.');
journal=jsondecode(fileread(Context.RawCaptureJournalPath));
assert(string(journal.Stage)=="RAW_CAPTURE_COMMITTED"&&journal.Sequence==4&& ...
    string(journal.Identity.ScientificRunId)==string(Context.ScientificRunId), ...
    'G4CRPreflight:ParentCheckpoint','Required RAW_CAPTURE_COMMITTED provenance is absent.');

assert(isfile(Context.DSALPath)&&hashLocal(Context.DSALPath)==string(Context.DSALSHA256), ...
    'G4CRPreflight:DSAL','DSAL is missing or SHA-mismatched.');
dsal=jsondecode(fileread(Context.DSALPath));
assert(string(dsal.State)=="GENERATED_UNACCEPTED"&&dsal.G4_RESULT_COUNT==0&& ...
    string(dsal.ScientificRunId)==string(Context.ScientificRunId), ...
    'G4CRPreflight:DSAL','DSAL pre-state is not GENERATED_UNACCEPTED / zero results.');
Receipt=struct('ValidationVersion','G4_COMPACT_RECOVERY_INPUT_PREFLIGHT_v1', ...
    'ScientificRunId',Context.ScientificRunId,'RosterIndex',Context.RosterIndex, ...
    'Seed',Context.Seed,'SourceEventFactsSHA256',Context.SourceEventFactsSHA256, ...
    'ParentCheckpoint','RAW_CAPTURE_COMMITTED','DSALState','GENERATED_UNACCEPTED', ...
    'G4_RESULT_COUNT',0,'M2TraversalCountDuringValidation',0, ...
    'RandomDrawCountDuringValidation',0,'RecoveryLockAcquired',false,'PASS',true);
end

function sha=hashLocal(path)
md=java.security.MessageDigest.getInstance('SHA-256');
fid=fopen(path,'r');assert(fid>=0,'G4CRPreflight:HashOpen','Cannot hash %s.',path);cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true,data=fread(fid,1024*1024,'*uint8');if isempty(data),break;end;md.update(typecast(data,'int8'));end
sha=string(lower(reshape(dec2hex(mod(double(md.digest()),256),2).',1,[])));
end
