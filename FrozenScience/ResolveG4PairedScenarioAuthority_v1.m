function Authority=ResolveG4PairedScenarioAuthority_v1(InputParams,AuthorityDefinitionPath)
% Resolve the G4 paired execution authority without changing G3 parent bytes.
arguments
    InputParams (1,1) struct
    AuthorityDefinitionPath (1,1) string
end

before=InputParams;
assert(isfile(AuthorityDefinitionPath),'G4SMAD:AuthorityDefinitionMissing', ...
    'Paired-scenario authority definition is missing.');
C=jsondecode(fileread(AuthorityDefinitionPath));
assert(string(C.ExecutionScenarioId)=="S0-D-G4-Paired-v1" && ...
    string(C.ParentScenarioId)=="S0-D-v1", ...
    'G4SMAD:AuthorityDefinitionIdentity','Paired-scenario authority identity is invalid.');
assert(isfield(InputParams,'ScenarioId') && ...
    string(InputParams.ScenarioId)==string(C.ExecutionScenarioId), ...
    'G4SMAD:ExecutionScenarioIdentity','Input ScenarioId is not the paired execution identity.');
assert(isfield(InputParams,'ExecutionScenarioId') && ...
    string(InputParams.ExecutionScenarioId)==string(C.ExecutionScenarioId), ...
    'G4SMAD:ExecutionScenarioIdentity','Input ExecutionScenarioId is not the paired execution identity.');
assert(isfield(InputParams,'ParentScenarioId') && ...
    string(InputParams.ParentScenarioId)==string(C.ParentScenarioId), ...
    'G4SMAD:ParentScenarioIdentity','Input ParentScenarioId is not S0-D-v1.');

resolverPath=string(C.ParentResolver.Path);
assert(isfile(resolverPath),'G4SMAD:ParentResolverMissing','Frozen parent resolver is missing.');
actualResolver=string(which('ResolveG3Parameters'));
assert(samePathLocal(actualResolver,resolverPath) && ...
    sha256FileLocal(resolverPath)==lower(string(C.ParentResolver.SHA256)) && ...
    dir(resolverPath).bytes==double(C.ParentResolver.Bytes), ...
    'G4SMAD:ParentResolverIdentity','Active parent resolver does not match the frozen authority.');

pairedMetadata={ ...
    'ExecutionScenarioId','ParentScenarioId','AuthorityVersion','AuthorityClass', ...
    'PaperScope','SourceType','FrequencyHz','ProductionRepresentation', ...
    'FormalFsHz','P20S','TauS','WformalStartS','WformalStopS', ...
    'RawSupportStartS','RawSupportStopS','TraversalModel', ...
    'ComparisonModel','M0CConstruction','PairedExecutionProvenance'};
parentProbe=InputParams;
present=pairedMetadata(isfield(parentProbe,pairedMetadata));
if ~isempty(present),parentProbe=rmfield(parentProbe,present);end
parentProbe.ScenarioId=char(C.ParentScenarioId);
assert(isfield(parentProbe,'Model') && isstruct(parentProbe.Model), ...
    'G4SMAD:ModelControlMissing','InputParams.Model is required.');
parentProbe.Model.DisableAdditionalRandomPhase=true;

% ParentProbe is authority resolution only. It is never an execution object.
[parentResolved,parentDerived,parentAudit]=ResolveG3Parameters(parentProbe,'single');
[executionResolved,executionDerived,executionAudit]=ResolveG3Parameters(InputParams,'single');

assert(isequaln(before,InputParams),'G4SMAD:ResolverMutatedInput', ...
    'Paired authority resolution must not mutate its input.');
Authority=struct( ...
    'AuthorityVersion',string(C.AuthorityVersion), ...
    'AuthorityDefinitionPath',char(AuthorityDefinitionPath), ...
    'AuthorityDefinitionSHA256',char(sha256FileLocal(AuthorityDefinitionPath)), ...
    'ExecutionScenarioId',string(C.ExecutionScenarioId), ...
    'ParentScenarioId',string(C.ParentScenarioId), ...
    'ParentResolverPath',char(resolverPath), ...
    'ParentResolverSHA256',char(sha256FileLocal(resolverPath)), ...
    'ParentProbeExecutionPermitted',false, ...
    'ParentProbe',parentProbe, ...
    'ParentResolved',parentResolved, ...
    'ParentDerived',parentDerived, ...
    'ParentAudit',parentAudit, ...
    'ExecutionResolved',executionResolved, ...
    'ExecutionDerived',executionDerived, ...
    'ExecutionAudit',executionAudit, ...
    'AllowedModelTreatmentDeltaWhitelist',{cellstr(string(C.AllowedModelTreatmentDeltaWhitelist))}, ...
    'ProductionImpulseResponseCalled',false, ...
    'M2TraversalCount',0,'RandomDrawCount',0,'Seed1Run',false);
end

function tf=samePathLocal(a,b)
tf=false;
if strlength(a)==0 || strlength(b)==0,return;end
tf=strcmpi(string(char(java.io.File(char(a)).getCanonicalPath())), ...
    string(char(java.io.File(char(b)).getCanonicalPath())));
end

function h=sha256FileLocal(p)
fid=fopen(p,'rb');assert(fid>0,'G4SMAD:HashOpenFailed','Cannot open %s.',p);
cleanup=onCleanup(@()fclose(fid)); %#ok<NASGU>
b=fread(fid,Inf,'*uint8');md=java.security.MessageDigest.getInstance('SHA-256');
d=typecast(md.digest(b),'uint8');h=string(lower(reshape(dec2hex(d,2).',1,[])));
end
