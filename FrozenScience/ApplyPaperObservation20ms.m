function [z,audit] = ApplyPaperObservation20ms(h,fs)
%ApplyPaperObservation20ms Apply the paper pulse and stable SOS exactly once.
arguments
    h {mustBeNumeric}
    fs (1,1) double {mustBeFinite,mustBePositive}
end
root=fileparts(mfilename('fullpath'));
g3=fileparts(root);
kernelRoot=fullfile(g3,'16_PreC1_FilterRepresentationAudit');
oldPath=path;cleanup=onCleanup(@()path(oldPath)); %#ok<NASGU>
addpath(kernelRoot,'-begin');
[pulse,~,pulseMeta]=GeneratePaperObservationPulse20ms(fs);
F=BuildCanonicalFormalBandpass(fs);
assert(all(abs(F.p)<1),'P20:UnstableSOS');
y=conv(h(:),pulse(:),'full');
z=ApplyAuditedStableBandpass(y,F,"SOS");
audit=struct( ...
    'ContractVersion','P20_PAPER_OBSERVER_v1', ...
    'InputSignalIdentity','narrowband_equivalent_complex_coefficient_impulse_response_at_1kHz', ...
    'ExplicitCarrierMultiplicationCount',0, ...
    'EventGenerationPulseApplicationCount',0, ...
    'RawHConstructionPulseApplicationCount',0, ...
    'Paper20msPulseApplicationCount',1, ...
    'StableSOSApplicationCount',1, ...
    'MetricAdditionalPulseApplicationCount',0, ...
    'ConvolutionScaling','discrete_sum_no_1_over_Fs', ...
    'PhysicalEnergyScaling','sum_abs_squared_divided_by_Fs', ...
    'PulseMeta',pulseMeta, ...
    'StableObserverVersion','MS_BPF_ZPK2SOS_Filtfilt_v1', ...
    'StableObserverCenterHz',F.CenterHz, ...
    'StableObserverLowerHz',F.LowerHz, ...
    'StableObserverUpperHz',F.UpperHz, ...
    'EffectiveKernelComposition','historical_20ms_shape_filter_then_convolution_then_canonical_ZPK_to_SOS_filtfilt', ...
    'RawInputSamples',numel(h),'ObservedSamples',numel(z));
end
