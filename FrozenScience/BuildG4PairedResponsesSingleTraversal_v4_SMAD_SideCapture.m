function Paired=BuildG4PairedResponsesSingleTraversal_v4_SMAD_SideCapture(InputParams,TempWorkDir,Contract,Context)
% SMAD candidate v4: immutable paired identity plus durable raw side capture.
arguments
    InputParams (1,1) struct
    TempWorkDir (1,1) string
    Contract (1,1) struct
    Context (1,1) struct
end
assert(Contract.G4ScientificExecutionAuthorized,'G4PB:NotAuthorized','G4PB:NotAuthorized');
G4ExclusiveTraversalLock_v1("VERIFY",Context.LockPath,Context.Identity,Context.LockToken);
assert(~isfile(fullfile(Context.Root,'AttemptJournal','02_TRAVERSAL_ENTERED.json')),'G4PB:NoSecondTraversal','G4PB:NoSecondTraversal');
% Authorization-bound scenario/model controls are validated, never mutated here.
assert(string(InputParams.ScenarioId)=="S0-D-G4-Paired-v1" && ...
    string(InputParams.ExecutionScenarioId)=="S0-D-G4-Paired-v1" && ...
    string(InputParams.ParentScenarioId)=="S0-D-v1", ...
    'G4SMAD:ExecutionScenarioIdentity','Paired scenario identity mismatch.');
assert(string(InputParams.TraversalModel)=="M2" && ...
    isequal(InputParams.Model.DisableAdditionalRandomPhase,false) && ...
    string(InputParams.RandomModel)=="event_white_phase" && ...
    string(InputParams.ScatterGrid.RandomModel)=="event_white_phase" && ...
    double(InputParams.RandomModelVersion)==double(Contract.RandomModelVersion) && ...
    double(InputParams.ScatterGrid.RandomModelVersion)==double(Contract.RandomModelVersion), ...
    'G4SMAD:M2TreatmentIdentity','Authorized M2 treatment identity mismatch.');
counts=struct('M2TraversalCount',1,'RandomDrawCount',[],'RandomDrawStatus','UNKNOWN_UNTIL_RETURN');
G4PhaseBJournal_v1(Context.Root,Context.Identity,"TRAVERSAL_ENTERED",counts);
[totalTime,hM2,hDir,m2Events,surfaceEvents,directEvents,randomInfo,g3Audit,gridAudit]= ...
    ImpulseResponse(InputParams,1,TempWorkDir);
% 注意：在原始保存之前不检查 randomInfo、不进行 M0-C 重构、不运行配对断言。
G4PhaseBJournal_v1(Context.Root,Context.Identity,"TRAVERSAL_RETURNED",counts);
facts=G4PhaseBIO_v1("MAT",fullfile(Context.Root,'RawEventFacts.mat'), ...
    struct('M2Events',m2Events,'SurfaceEvents',surfaceEvents,'DirectEvents',directEvents));
raw=G4PhaseBIO_v1("MAT",fullfile(Context.Root,'RawResponses.mat'), ...
    struct('M2hSca',hM2,'CommonhDir',hDir,'TotalTime',totalTime));
metadata=G4PhaseBIO_v1("MAT",fullfile(Context.Root,'RawMetadata.mat'), ...
    struct('RandomInfo',randomInfo,'G3Audit',g3Audit,'GridAudit',gridAudit,'InputParams',InputParams));
% Evidence #5 prospective closure. These three deterministic reconstructions
% consume only the event facts returned by the sole M2 traversal.
eventY=double([m2Events.Y]);
hPlus=BuildImpulseResponseFromEvents(m2Events(eventY>0),InputParams.fs,numel(hM2));
hMinus=BuildImpulseResponseFromEvents(m2Events(eventY<0),InputParams.fs,numel(hM2));
hAxis=BuildImpulseResponseFromEvents(m2Events(eventY==0),InputParams.fs,numel(hM2));
closureResidual=hM2(:)-hPlus(:)-hMinus(:)-hAxis(:);
sidePayload=struct('hTotal',hM2(:),'hPlus',hPlus(:),'hMinus',hMinus(:),'hAxis',hAxis(:), ...
    'ScientificRunId',Context.Identity.ScientificRunId, ...
    'RosterIndex',Context.Identity.RosterIndex,'Seed',Context.Identity.Seed, ...
    'PayloadSHA',Context.Identity.SeedPayloadSHA256,'RMV',Context.Identity.RandomModelVersion, ...
    'SourceEventFactsSHA',facts.SHA256, ...
    'SideReconstructionHelperSHA256',Contract.ActiveSourceSHAs.BuildImpulseResponseFromEvents, ...
    'RawPartitionResidualMaxAbs',max(abs(closureResidual),[],'omitnan'), ...
    'RawPartitionResidualL2',norm(closureResidual), ...
    'RawPartitionResidualRole','SUPPORTING_DIAGNOSTIC_NOT_EVIDENCE_8_ADJUDICATION');
side=G4PhaseBIO_v1("MAT",fullfile(Context.Root,'RawM2SideResponses.mat'),sidePayload);
capsule=struct('Identity',Context.Identity,'Stage','RAW_CAPTURE_COMMITTED', ...
    'SourceEventFactsSHA256',facts.SHA256,'Artifacts',[facts raw metadata side], ...
    'AvailableSides','hTotal/hPlus/hMinus/hAxis reconstructed from the same returned M2Events', ...
    'RawM2SideResponsesSHA256',side.SHA256, ...
    'M0CConstructionAttempted',false);
capsuleReceipt=G4PhaseBIO_v1("JSON",fullfile(Context.Root,'RawCaptureManifest.json'),capsule);
G4PhaseBJournal_v1(Context.Root,Context.Identity,"RAW_CAPTURE_COMMITTED",counts,capsuleReceipt);
UpdateG4Seed1AcceptanceLedger_v1(Context.Identity.DSALPath,Context.LedgerSHA256,"MARK_GENERATED",Context.Identity);
% 从这一行起，即使 pairing 抛错，全部实际输出均可由 capsule SHA 定位。
assert(randomInfo.RandomModelVersion==Contract.RandomModelVersion,'G4PB:RMVMismatch','G4PB:RMVMismatch');
assert(double(randomInfo.RandomSeedUsed)==Context.Identity.Seed,'G4PB:SeedMismatch','G4PB:SeedMismatch');
assert(string(randomInfo.RandomModel)=="event_white_phase" && string(randomInfo.RandomSeedMode)=="specified",'G4PB:RandomIdentity','G4PB:RandomIdentity');
counts.RandomDrawCount=1;counts.RandomDrawStatus='ONE_FROZEN_REALIZATION_RESOLUTION';
identityReceipt=G4PhaseBIO_v1("JSON",fullfile(Context.Root,'ReturnedRandomIdentity.json'), ...
    struct('Identity',Context.Identity,'Counts',counts,'RandomInfo',randomInfo,'SourceEventFactsSHA256',facts.SHA256));
m0cEvents=BuildProductionM0CFromM2Events_v1(m2Events);
m0Receipt=G4PhaseBIO_v1("MAT",fullfile(Context.Root,'M0CEvents.mat'),struct('M0CEvents',m0cEvents));
forensic=G4PairingForensics_v1(m0cEvents,m2Events);
forensic.Identity=Context.Identity;forensic.SourceEventFactsSHA256=facts.SHA256;
forensic.SourceSHAs=Contract.ActiveSourceSHAs;
fReceipt=G4PhaseBIO_v1("JSON",fullfile(Context.Root,'PairingForensics.json'),forensic);
% 原冻结 evaluator 不改；无 OutputStem 避免其非事务写入。异常由外层封存。
try
    manifest=VerifyRuntimeCommonEventPairingGate_v1(randomInfo.RandomSeedUsed,m0cEvents,m2Events, ...
        "G4_COMMON_EVENT_TUPLE_v1",Contract.ActiveSourceSHAs,"");
    assert(forensic.PASS,'G4PB:SupplementalDuplicateOrMissing','Supplemental unique-key gate failed.');
    verdict=struct('PASS',true,'Manifest',manifest,'ErrorIdentifier','','ErrorMessage','');
catch ME
    verdict=struct('PASS',false,'Manifest',struct(),'ErrorIdentifier',ME.identifier,'ErrorMessage',ME.message);
    vReceipt=G4PhaseBIO_v1("JSON",fullfile(Context.Root,'PairingVerdict.json'),verdict);
    G4PhaseBJournal_v1(Context.Root,Context.Identity,"PAIRING_EVALUATED",counts,[identityReceipt m0Receipt fReceipt vReceipt]);
    rethrow(ME);
end
vReceipt=G4PhaseBIO_v1("JSON",fullfile(Context.Root,'PairingVerdict.json'),verdict);
G4PhaseBJournal_v1(Context.Root,Context.Identity,"PAIRING_EVALUATED",counts,[identityReceipt m0Receipt fReceipt vReceipt]);
% 与旧 helper PASS 路径保持数值一致；不据此发布 Evidence #9。
hM0C=BuildImpulseResponseFromEvents(m0cEvents,InputParams.fs,numel(hM2));
G4PhaseBIO_v1("MAT",fullfile(Context.Root,'PairedRawResponses.mat'),struct('M0ChSca',hM0C,'M2hSca',hM2,'CommonhDir',hDir));
Paired=struct('RandomInfo',randomInfo,'M0CEvents',m0cEvents,'M2Events',m2Events, ...
    'M0ChSca',hM0C,'M2hSca',hM2,'CommonhDir',hDir,'DirectEvents',directEvents, ...
    'M2hPlus',hPlus,'M2hMinus',hMinus,'M2hAxis',hAxis, ...
    'GridAudit',gridAudit,'PairingManifest',manifest,'SameTraversalEventTableAndH',true, ...
    'SecondRandomDrawPossible',false,'SaveEventsRerunProhibited',true, ...
    'RawCaptureManifest',capsuleReceipt,'RawSideReceipt',side, ...
    'Forensics',forensic,'Counts',counts);
end
