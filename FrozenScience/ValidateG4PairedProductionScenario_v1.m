function Audit=ValidateG4PairedProductionScenario_v1(InputParams,Authority,ThrowOnFailure)
% Non-mutating, row-wise invariant gate for S0-D-G4-Paired-v1.
arguments
    InputParams (1,1) struct
    Authority (1,1) struct
    ThrowOnFailure (1,1) logical = true
end

before=InputParams;
rows=struct('ControlName',{},'ExpectedValue',{},'ActualValue',{}, ...
    'MetricAuthoritySource',{},'Classification',{},'PASS',{});
add('ScenarioId','S0-D-G4-Paired-v1',fieldText(InputParams,'ScenarioId'), ...
    'InputParams.ScenarioId','PROVENANCE_METADATA', ...
    fieldString(InputParams,'ScenarioId')=="S0-D-G4-Paired-v1");
add('ExecutionScenarioId','S0-D-G4-Paired-v1',fieldText(InputParams,'ExecutionScenarioId'), ...
    'InputParams.ExecutionScenarioId','PROVENANCE_METADATA', ...
    fieldString(InputParams,'ExecutionScenarioId')=="S0-D-G4-Paired-v1");
add('ParentScenarioId','S0-D-v1',fieldText(InputParams,'ParentScenarioId'), ...
    'InputParams.ParentScenarioId','PROVENANCE_METADATA', ...
    fieldString(InputParams,'ParentScenarioId')=="S0-D-v1");
add('PaperScope','bottom-only',fieldText(InputParams,'PaperScope'), ...
    'InputParams.PaperScope','INHERITED_PHYSICAL_NUMERICAL', ...
    fieldString(InputParams,'PaperScope')=="bottom-only");
add('SourceType','omnidirectional',fieldText(InputParams,'SourceType'), ...
    'InputParams.SourceType','INHERITED_PHYSICAL_NUMERICAL', ...
    fieldString(InputParams,'SourceType')=="omnidirectional");
add('FrequencyHz','1000',numberText(InputParams,'FrequencyHz'), ...
    'InputParams.FrequencyHz and f0','INHERITED_PHYSICAL_NUMERICAL', ...
    scalarEqual(InputParams,'FrequencyHz',1000) && scalarEqual(InputParams,'f0',1000));
add('ProductionRepresentation','M50',fieldText(InputParams,'ProductionRepresentation'), ...
    'InputParams.ProductionRepresentation plus GridI/GridIPlusM','INHERITED_PHYSICAL_NUMERICAL', ...
    fieldString(InputParams,'ProductionRepresentation')=="M50" && ...
    nestedScalarEqual(InputParams,{'DomainResolved','GridI'},30) && ...
    nestedScalarEqual(InputParams,{'DomainResolved','GridIPlusM'},100));
add('RmaxM','50000',nestedNumberText(InputParams,{'DomainResolved','RmaxM'}), ...
    'InputParams.DomainResolved.RmaxM','INHERITED_PHYSICAL_NUMERICAL', ...
    nestedScalarEqual(InputParams,{'DomainResolved','RmaxM'},50000));
add('BellhopLaunchAngleStepDeg','0.01', ...
    nestedNumberText(InputParams,{'DomainResolved','BellhopLaunchAngleStepDeg'}), ...
    'InputParams.DomainResolved.BellhopLaunchAngleStepDeg','INHERITED_PHYSICAL_NUMERICAL', ...
    nestedScalarEqual(InputParams,{'DomainResolved','BellhopLaunchAngleStepDeg'},0.01));
add('FormalFsHz','256000',numberText(InputParams,'FormalFsHz'), ...
    'InputParams.FormalFsHz/Fs/fs','INHERITED_PHYSICAL_NUMERICAL', ...
    scalarEqual(InputParams,'FormalFsHz',256000) && scalarEqual(InputParams,'Fs',256000) && scalarEqual(InputParams,'fs',256000));
add('P20S','0.02',numberText(InputParams,'P20S'), ...
    'InputParams.P20S/Itg','INHERITED_PHYSICAL_NUMERICAL', ...
    scalarEqual(InputParams,'P20S',0.02) && scalarEqual(InputParams,'Itg',0.02));
add('TauS','0.002',numberText(InputParams,'TauS'), ...
    'InputParams.TauS; observer contract identity','INHERITED_PHYSICAL_NUMERICAL', ...
    scalarEqual(InputParams,'TauS',0.002));
add('Wformal','[0,60 s)',intervalText(InputParams,'WformalStartS','WformalStopS'), ...
    'InputParams.WformalStartS/WformalStopS/FormalAnalysisWindowS','INHERITED_PHYSICAL_NUMERICAL', ...
    scalarEqual(InputParams,'WformalStartS',0) && scalarEqual(InputParams,'WformalStopS',60) && ...
    scalarEqual(InputParams,'FormalAnalysisWindowS',60));
add('RawSupport','[0,60.2 s)',intervalText(InputParams,'RawSupportStartS','RawSupportStopS'), ...
    'InputParams.RawSupportStartS/RawSupportStopS/TWindow','INHERITED_PHYSICAL_NUMERICAL', ...
    scalarEqual(InputParams,'RawSupportStartS',0) && scalarEqual(InputParams,'RawSupportStopS',60.2) && ...
    scalarEqual(InputParams,'TWindow',60.2) && scalarEqual(InputParams,'ProductionTWindowComputeS',60.2));
add('Beam.AzimuthRange','[-180,180]',nestedArrayText(InputParams,{'Beam','AzimuthRange'}), ...
    'InputParams.Beam.AzimuthRange','INHERITED_PHYSICAL_NUMERICAL', ...
    nestedArrayEqual(InputParams,{'Beam','AzimuthRange'},[-180 180]));
add('Beam.OpenAngle','[90,-90]',nestedArrayText(InputParams,{'Beam','OpenAngle'}), ...
    'InputParams.Beam.OpenAngle','INHERITED_PHYSICAL_NUMERICAL', ...
    nestedArrayEqual(InputParams,{'Beam','OpenAngle'},[90 -90]));
add('Beam.MainBeam','[90,-90]',nestedArrayText(InputParams,{'Beam','MainBeam'}), ...
    'InputParams.Beam.MainBeam','INHERITED_PHYSICAL_NUMERICAL', ...
    nestedArrayEqual(InputParams,{'Beam','MainBeam'},[90 -90]));
add('Beam.SideDown_dB','0',nestedNumberText(InputParams,{'Beam','SideDown_dB'}), ...
    'InputParams.Beam.SideDown_dB','INHERITED_PHYSICAL_NUMERICAL', ...
    nestedScalarEqual(InputParams,{'Beam','SideDown_dB'},0));
suspicious=directionalInputFieldsLocal(InputParams);
add('DirectionalSourceDependency','NONE',strjoin(suspicious,','), ...
    'Recursive InputParams field-name audit; code/dependency audit is separately SHA-bound', ...
    'INHERITED_PHYSICAL_NUMERICAL',isempty(suspicious));
add('TraversalModel','M2',fieldText(InputParams,'TraversalModel'), ...
    'InputParams.TraversalModel','ALLOWED_MODEL_TREATMENT_DELTA', ...
    fieldString(InputParams,'TraversalModel')=="M2");
add('DisableAdditionalRandomPhase','false',nestedNumberText(InputParams,{'Model','DisableAdditionalRandomPhase'}), ...
    'InputParams.Model.DisableAdditionalRandomPhase','ALLOWED_MODEL_TREATMENT_DELTA', ...
    nestedLogicalEqual(InputParams,{'Model','DisableAdditionalRandomPhase'},false));
add('RandomModel','event_white_phase',fieldText(InputParams,'RandomModel'), ...
    'InputParams.RandomModel/ScatterGrid.RandomModel','ALLOWED_MODEL_TREATMENT_DELTA', ...
    fieldString(InputParams,'RandomModel')=="event_white_phase" && ...
    nestedStringEqual(InputParams,{'ScatterGrid','RandomModel'},"event_white_phase"));
add('RandomModelVersion','1',numberText(InputParams,'RandomModelVersion'), ...
    'InputParams.RandomModelVersion/ScatterGrid.RandomModelVersion','ALLOWED_MODEL_TREATMENT_DELTA', ...
    scalarEqual(InputParams,'RandomModelVersion',1) && nestedScalarEqual(InputParams,{'ScatterGrid','RandomModelVersion'},1));
add('ComparisonModel','M0-C',fieldText(InputParams,'ComparisonModel'), ...
    'InputParams.ComparisonModel','ALLOWED_MODEL_TREATMENT_DELTA', ...
    fieldString(InputParams,'ComparisonModel')=="M0-C");
add('M0CConstruction','reconstruction_from_same_M2_event_facts',fieldText(InputParams,'M0CConstruction'), ...
    'InputParams.M0CConstruction','ALLOWED_MODEL_TREATMENT_DELTA', ...
    fieldString(InputParams,'M0CConstruction')=="reconstruction_from_same_M2_event_facts");
add('AuthorityIdentity','S0-D-G4-Paired-v1 <- S0-D-v1', ...
    string(Authority.ExecutionScenarioId)+" <- "+string(Authority.ParentScenarioId), ...
    'ResolveG4PairedScenarioAuthority_v1 output','PROVENANCE_METADATA', ...
    string(Authority.ExecutionScenarioId)=="S0-D-G4-Paired-v1" && string(Authority.ParentScenarioId)=="S0-D-v1");
add('ParentProbeNotExecutable','true',string(~Authority.ParentProbeExecutionPermitted), ...
    'ResolveG4PairedScenarioAuthority_v1 output','PROVENANCE_METADATA', ...
    ~Authority.ParentProbeExecutionPermitted);
add('ExecutionResolverRetainsM2','false', ...
    string(Authority.ExecutionResolved.Model.DisableAdditionalRandomPhase), ...
    'ExecutionResolved.Model.DisableAdditionalRandomPhase','ALLOWED_MODEL_TREATMENT_DELTA', ...
    isequal(Authority.ExecutionResolved.Model.DisableAdditionalRandomPhase,false));

assert(isequaln(before,InputParams),'G4SMAD:ValidatorMutatedInput', ...
    'Paired-scenario validator must not mutate its input.');
Audit=struct('Version','ValidateG4PairedProductionScenario_v1', ...
    'ExecutionScenarioId','S0-D-G4-Paired-v1','ParentScenarioId','S0-D-v1', ...
    'Rows',rows,'RowCount',numel(rows),'PassCount',sum([rows.PASS]), ...
    'FailCount',sum(~[rows.PASS]),'AllPass',all([rows.PASS]), ...
    'InputMutated',false,'ProductionImpulseResponseCalled',false, ...
    'M2TraversalCount',0,'RandomDrawCount',0,'Seed1Run',false);
if ThrowOnFailure && ~Audit.AllPass
    failed=string({rows(~[rows.PASS]).ControlName});
    error('G4SMAD:ProductionScenarioValidationFailed', ...
        'Paired production scenario failed: %s.',strjoin(failed,','));
end

    function add(name,expected,actual,source,classification,pass)
        rows(end+1)=struct('ControlName',char(name),'ExpectedValue',char(string(expected)), ...
            'ActualValue',char(string(actual)),'MetricAuthoritySource',char(string(source)), ...
            'Classification',char(string(classification)),'PASS',logical(pass));
    end
end

function s=fieldString(P,name),if isfield(P,name)&&~isempty(P.(name)),s=string(P.(name));else,s="<MISSING>";end,end
function s=fieldText(P,name),s=fieldString(P,name);end
function s=numberText(P,name),if isfield(P,name)&&isscalar(P.(name)),s=string(double(P.(name)));else,s="<MISSING_OR_NONSCALAR>";end,end
function tf=scalarEqual(P,name,value),tf=isfield(P,name)&&isscalar(P.(name))&&isequaln(double(P.(name)),double(value));end
function s=intervalText(P,a,b),if scalarEqual(P,a,0)&&isfield(P,b)&&isscalar(P.(b)),s="[0,"+string(double(P.(b)))+" s)";else,s="<INVALID>";end,end
function [ok,v]=nestedValue(P,path),v=P;ok=true;for k=1:numel(path),if ~isstruct(v)||~isfield(v,path{k}),ok=false;v=[];return;end;v=v.(path{k});end,end
function tf=nestedScalarEqual(P,path,value),[ok,v]=nestedValue(P,path);tf=ok&&isscalar(v)&&isequaln(double(v),double(value));end
function tf=nestedLogicalEqual(P,path,value),[ok,v]=nestedValue(P,path);tf=ok&&isscalar(v)&&isequal(logical(v),logical(value));end
function tf=nestedStringEqual(P,path,value),[ok,v]=nestedValue(P,path);tf=ok&&isscalar(string(v))&&string(v)==string(value);end
function tf=nestedArrayEqual(P,path,value),[ok,v]=nestedValue(P,path);tf=ok&&isequaln(double(v(:).'),double(value(:).'));end
function s=nestedNumberText(P,path),[ok,v]=nestedValue(P,path);if ok&&isscalar(v),s=string(double(v));else,s="<MISSING_OR_NONSCALAR>";end,end
function s=nestedArrayText(P,path),[ok,v]=nestedValue(P,path);if ok,s="["+strjoin(string(double(v(:).')),",")+"]";else,s="<MISSING>";end,end
function names=directionalInputFieldsLocal(P)
names=strings(0,1);walk(P,"");
    function walk(S,prefix)
        if ~isstruct(S)||~isscalar(S),return;end
        f=fieldnames(S);
        for j=1:numel(f)
            q=string(f{j});full=prefix+q;
            if ~isempty(regexpi(char(q),'sbp|sourcepattern|directionalsource|beamfile','once'))
                names(end+1,1)=full; %#ok<AGROW>
            end
            if isstruct(S.(f{j}))&&isscalar(S.(f{j})),walk(S.(f{j}),full+".");end
        end
    end
end
