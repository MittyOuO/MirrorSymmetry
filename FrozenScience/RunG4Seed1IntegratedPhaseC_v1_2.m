function Result = RunG4Seed1IntegratedPhaseC_v1_2(AuthorizationArtifactPath,AuthorizationArtifactSHA256,OutputRoot)
%RunG4Seed1IntegratedPhaseC_v1_2 Pairing-adapted, grid-guarded deterministic Phase-C execution.
% The runner consumes only accepted Seed-1 raw responses. It does not call
% propagation, ImpulseResponse, event traversal, event regeneration, or RNG.
arguments
    AuthorizationArtifactPath (1,1) string
    AuthorizationArtifactSHA256 (1,1) string
    OutputRoot (1,1) string
end

started=tic;
pre=[];
A=[];
assert(isfile(AuthorizationArtifactPath),'G4PhaseC:AuthorizationMissing','Authorization artifact is missing.');
assert(hashLocal(AuthorizationArtifactPath)==lower(AuthorizationArtifactSHA256), ...
    'G4PhaseC:AuthorizationSHAMismatch','Authorization artifact SHA mismatch.');
A=jsondecode(fileread(AuthorizationArtifactPath));
validateAuthorizationLocal(A,AuthorizationArtifactPath,AuthorizationArtifactSHA256,OutputRoot);
assert(~isfolder(OutputRoot),'G4PhaseC:OutputExists','Fresh Phase-C output root already exists.');
assert(~isfolder(string(A.LargeDataOutputRootF)),'G4PhaseC:LargeOutputExists','Fresh Phase-C large-data root already exists.');
mkdir(OutputRoot);mkdir(string(A.LargeDataOutputRootF));
dirs=["Integrity","SciencePayload","RuntimeAuthority","ObservedIntegrity", ...
    "MetricIntegrity","DnumBinding","D1MCTIntegrity","SideIntegrity", ...
    "EnvelopeVectorIntegrity","QRIntegrity","Retention","GateEvidence", ...
    "PostRARC","Final"];
for k=1:numel(dirs),mkdir(fullfile(OutputRoot,dirs(k)));end

try
    oldPath=path;cleanupPath=onCleanup(@()path(oldPath)); %#ok<NASGU>
    roots=string(A.PathRoots(:));
    for k=numel(roots):-1:1,addpath(roots(k),'-begin');end

    binding=authorizationBindingLocal(A,AuthorizationArtifactPath,AuthorizationArtifactSHA256);
    writeJsonLocal(fullfile(OutputRoot,'RuntimeAuthority','PhaseC_AuthorizationBinding.json'),binding);
    sourceAudit=verifySourceRegistryLocal(A);
    writeJsonLocal(fullfile(OutputRoot,'Integrity','PhaseC_EntrySourceAuthorityAudit_v1.json'),sourceAudit);
    storageAudit=storageAuditLocal(A,OutputRoot);
    writeJsonLocal(fullfile(OutputRoot,'Integrity','PhaseC_StoragePreflight_v1.json'),storageAudit);

    pre=rarcLocal(A,"PHASE_C_PRE");
    assert(pre.AllPass,'G4PhaseC:PreRARC','Phase-C PRE-RARC failed.');
    writeRarcLocal(pre,fullfile(OutputRoot,'RuntimeAuthority','PhaseC_v1_2_PRE_RARC.json'), ...
        fullfile(OutputRoot,'RuntimeAuthority','PhaseC_v1_2_PRE_RARC.csv'));

    dsal=jsondecode(fileread(string(A.DSAL.Path)));
    assert(string(dsal.State)=="GENERATED_UNACCEPTED"&&double(dsal.G4_RESULT_COUNT)==0&& ...
        string(dsal.ScientificRunId)==string(A.ScientificRunId), ...
        'G4PhaseC:DSALState','DSAL is not GENERATED_UNACCEPTED with G4_RESULT_COUNT=0.');

    % C1: consume only the two accepted retained raw-response authorities.
    raw=load(string(A.RawM2SideResponses.Path),'hTotal','hPlus','hMinus','hAxis', ...
        'ScientificRunId','RosterIndex','Seed','PayloadSHA','RMV','SourceEventFactsSHA');
    m0c=load(string(A.M0CRawResponse.Path),'hM0C','ScientificRunId', ...
        'RecoveryExecutionId','SourceEventFactsSHA256','AlgebraicIdentityVersion');
    validateRawIdentityLocal(raw,m0c,A);
    fs=double(A.ProductionContract.FormalFsHz);
    [response,sideObserverAudit]=ApplyPaperObservation20msToSideResponses( ...
        raw.hTotal,raw.hPlus,raw.hMinus,raw.hAxis,fs);
    [zM0C,m0cObserverAudit]=ApplyPaperObservation20ms(m0c.hM0C,fs);

    % C1/C2 boundary: observed closure precedes every QoI calculation.
    closureHelper=VerifyG4SyntheticResponseClosure_v1(raw.hTotal(:),raw.hPlus(:), ...
        raw.hMinus(:),raw.hAxis(:),response.zTotal(:),response.zPlus(:), ...
        response.zMinus(:),response.zAxis(:),double(A.ObservedClosureTolerance));
    residual=response.zTotal(:)-(response.zPlus(:)+response.zMinus(:)+response.zAxis(:));
    observedClosure=struct('AuditVersion','G4_SEED1_PHASE_C_OBSERVED_CLOSURE_v1', ...
        'ScientificRunId',A.ScientificRunId,'PhaseCExecutionId',A.PhaseCExecutionId, ...
        'IdentityEquation','zTotal = zPlus + zMinus + zAxis', ...
        'MaxAbsResidual',max(abs(residual)),'AbsoluteL2Residual',norm(residual), ...
        'RelativeL2Residual',norm(residual)/max(1,norm(response.zTotal)), ...
        'NonzeroResidualBinCount',nnz(residual~=0),'SampleCount',numel(response.zTotal), ...
        'Tolerance',double(A.ObservedClosureTolerance), ...
        'ToleranceAuthorityPath',A.ObservedClosureToleranceAuthority.Path, ...
        'ToleranceAuthoritySHA256',A.ObservedClosureToleranceAuthority.SHA256, ...
        'FrozenHelperAudit',closureHelper,'ObserverIdentity','P20_20MS_EXACTLY_ONCE', ...
        'Evidence8','ACTUAL_PASS_RAW_AND_OBSERVED_CLOSURE_CANDIDATE', ...
        'PASS',true,'CreatedUTC',utcLocal());
    writeJsonLocal(fullfile(OutputRoot,'ObservedIntegrity','Evidence8_ObservedClosureAudit_v1.json'),observedClosure);
    clear residual

    zTotal=response.zTotal(:);zPlus=response.zPlus(:);zMinus=response.zMinus(:);zAxis=response.zAxis(:); %#ok<NASGU>
    observedMeta=struct('ScientificRunId',A.ScientificRunId,'PhaseCExecutionId',A.PhaseCExecutionId, ...
        'SourceRawM2Path',A.RawM2SideResponses.Path,'SourceRawM2SHA256',A.RawM2SideResponses.SHA256, ...
        'SourceM0CPath',A.M0CRawResponse.Path,'SourceM0CSHA256',A.M0CRawResponse.SHA256, ...
        'ObserverContractPath',A.ObserverContract.Path,'ObserverContractSHA256',A.ObserverContract.SHA256, ...
        'FormalFsHz',fs,'FormalWindow','[0,60 s)','RawSupport','[0,60.2 s)', ...
        'SideObserverAudit',sideObserverAudit,'M0CObserverAudit',m0cObserverAudit, ...
        'CreatedUTC',utcLocal()); %#ok<NASGU>
    observedPath=string(A.LargeDataOutputRootF)+filesep+"PhaseC_ObservedResponses_v1.mat";
    save(observedPath,'zTotal','zPlus','zMinus','zAxis','zM0C','observedMeta','-v7.3');
    observedFile=fileRecordLocal('ObservedResponses',observedPath);
    observedRecord=struct('RecordVersion','G4_SEED1_PHASE_C_OBSERVED_OBJECT_v1', ...
        'ScientificRunId',A.ScientificRunId,'PhaseCExecutionId',A.PhaseCExecutionId, ...
        'Object',observedFile,'SourceRawM2SHA256',A.RawM2SideResponses.SHA256, ...
        'SourceM0CSHA256',A.M0CRawResponse.SHA256,'ObserverContractSHA256',A.ObserverContract.SHA256, ...
        'ObservedSampleCount',numel(zTotal),'FormalFsHz',fs,'PASS',true,'CreatedUTC',utcLocal());
    writeJsonLocal(fullfile(OutputRoot,'ObservedIntegrity','PhaseC_ObservedObjectRecord_v1.json'),observedRecord);

    % C2: exact native 10-QoI pipeline.
    [metricM0C,envelopeM0C,peaksM0C]=ComputePaperResponseMetrics20ms_v2(zM0C,fs,0,60,"M0-C"); %#ok<NASGU>
    [metricM2,envelopeM2,peaksM2]=ComputePaperResponseMetrics20ms_v2(zTotal,fs,0,60,"M2"); %#ok<NASGU>
    native=BuildG4NativeMetricTable_v1(metricM0C,metricM2);
    native.SourceObservedObjectSHA256=repmat(string(observedFile.SHA256),height(native),1);
    native.MetricHelperSHA256=repmat(string(A.HelperSHA.ComputePaperResponseMetrics20ms_v2),height(native),1);
    metricReport=ValidateG4NativeMetricPipeline_v1(native,string(A.Dnum.Path),string(A.Dnum.SHA256));
    assert(metricReport.AllPass,'G4PhaseC:NativeMetricPipeline','Native 10-QoI pipeline validation failed.');
    nativePath=fullfile(OutputRoot,'SciencePayload','PhaseC_Native10QoI_v1.csv');
    writetable(native,nativePath,'Encoding','UTF-8');
    nativeFile=fileRecordLocal('ScalarQoITable',nativePath);
    metricIntegrity=struct('IntegrityVersion','G4_SEED1_PHASE_C_NATIVE_METRIC_INTEGRITY_v1', ...
        'QoICount',height(native),'ExactOrder',true,'NoMissingOrDuplicate',true, ...
        'MetricClassesExact',true,'MCTClassesExact',true,'RowState',{cellstr(metricReport.RowState)}, ...
        'FrozenValidatorPath',A.HelperPath.ValidateG4NativeMetricPipeline_v1, ...
        'FrozenValidatorSHA256',A.HelperSHA.ValidateG4NativeMetricPipeline_v1, ...
        'SciencePayloadObject',nativeFile,'Evidence10LookupReady',true, ...
        'Evidence11NativePipelineReady',true,'PASS',true,'CreatedUTC',utcLocal());
    writeJsonLocal(fullfile(OutputRoot,'MetricIntegrity','PhaseC_NativeMetricIntegrity_v1.json'),metricIntegrity);

    % C3: exact lookup-only D_num binding.
    dnum=readtable(string(A.Dnum.Path),'FileType','text','Delimiter',',','TextType','string', ...
        'VariableNamingRule','preserve','Encoding','UTF-8');
    assert(height(dnum)==10&&isequal(string(dnum.QoI),string(native.QoI)), ...
        'G4PhaseC:DnumRows','Frozen D_num row identity/order mismatch.');
    dnumBinding=struct('BindingVersion','G4_SEED1_PHASE_C_DNUM_LOOKUP_ONLY_v1', ...
        'DnumAuthorityPath',A.Dnum.Path,'DnumBytes',double(A.Dnum.Bytes), ...
        'DnumSHA256',A.Dnum.SHA256,'QoICount',height(dnum),'ExactOrderedLookup',true, ...
        'DnumRecomputed',false,'DnumReselected',false,'DnumInterpolated',false, ...
        'MCTInflation',false,'Evidence10','ACTUAL_PASS_CANDIDATE','PASS',true,'CreatedUTC',utcLocal());
    writeJsonLocal(fullfile(OutputRoot,'DnumBinding','PhaseC_DnumBinding_v1.json'),dnumBinding);

    % C4: D1/MCT. Actual values remain in SciencePayload only.
    n=height(native);
    signedDQ=NaN(n,1);absDQ=NaN(n,1);Rmodel=NaN(n,1);ratioValid=false(n,1);
    ratioState=strings(n,1);cmpDelta=NaN(n,1);mctValue=NaN(n,1);classification=strings(n,1);
    legal=false(n,1);retain=false(n,1);replace=false(n,1);extend=false(n,1);
    for k=1:n
        cls=string(native.MetricClass(k));mct=mctForClassLocal(A,cls);
        o=EvaluateG4ScalarD1MCT_v2(double(native.Q_M0C(k)),double(native.Q_M2(k)), ...
            double(dnum.D_num(k)),cls,logical(native.StructuralPrerequisite(k)),mct);
        if cls=="POSITIVE_RELATIVE_LINEAR",signedDQ(k)=o.RelativeDifference;else,signedDQ(k)=o.SignedNativeDifference;end
        absDQ(k)=abs(signedDQ(k));Rmodel(k)=o.R_model;ratioValid(k)=o.D1Valid;
        ratioState(k)=o.RatioState;cmpDelta(k)=o.ComparatorDelta;mctValue(k)=o.MCT;
        classification(k)=o.Classification;legal(k)=o.LegalSpecialOutcome;
        retain(k)=o.RetainSeed;replace(k)=o.ReplaceSeed;extend(k)=o.ExtendN;
    end
    d1=table(native.QoI,native.MetricClass,native.Q_M0C,native.Q_M2,signedDQ,absDQ, ...
        double(dnum.D_num),Rmodel,ratioValid,ratioState,cmpDelta,mctValue,classification, ...
        legal,retain,replace,extend,'VariableNames',{'QoI','MetricClass','Q_M0C','Q_M2', ...
        'Signed_d_Q','Abs_d_Q','D_num','R_model','RatioValid','RatioState','ComparatorDelta', ...
        'MCT','Classification','LegalSpecialOutcome','RetainSeed','ReplaceSeed','ExtendN'});
    assert(all(retain)&&~any(replace)&&~any(extend),'G4PhaseC:D1SeedGovernance','D1/MCT seed governance changed.');
    d1Path=fullfile(OutputRoot,'SciencePayload','PhaseC_D1MCT_Actual_v1.csv');
    writetable(d1,d1Path,'Encoding','UTF-8');
    d1Integrity=struct('IntegrityVersion','G4_SEED1_PHASE_C_D1_MCT_INTEGRITY_v1', ...
        'RowCount',height(d1),'AllowedStatesOnly',all(ismember(classification, ...
        ["ABOVE","BELOW","MACHINE_BOUNDARY_INDETERMINATE","RATIO_INVALID_NOT_CLASSIFIABLE"])), ...
        'Classification',{cellstr(classification)},'LegalSpecialOutcomeCount',nnz(legal), ...
        'RetainSeedAll',all(retain),'ReplaceSeedAny',any(replace),'ExtendNAny',any(extend), ...
        'SciencePayloadObject',fileRecordLocal('D1MCT',d1Path),'PASS',true,'CreatedUTC',utcLocal());
    writeJsonLocal(fullfile(OutputRoot,'D1MCTIntegrity','PhaseC_D1MCTIntegrity_v1.json'),d1Integrity);

    % C5: structural side route only; no scalar side R_model or borrowed D_num.
    sideMetrics=ComputePaperMirrorMetrics20ms(zPlus,zMinus,raw.hPlus,raw.hMinus,fs);
    sideNames=["abs(A_E)";"D_pm";"signed A_E";"C_pm"];
    sideValues=[abs(sideMetrics.A_E);sideMetrics.D_pm;sideMetrics.A_E;sideMetrics.C_pm];
    for k=1:4,EnforceG4SideMetricRoute_v1(sideNames(k),"COMPUTE_STRUCTURAL_METRIC");end
    sideTable=table(sideNames,sideValues,repmat(string(observedFile.SHA256),4,1), ...
        repmat(string(A.HelperSHA.ComputePaperMirrorMetrics20ms),4,1), ...
        'VariableNames',{'Metric','Value','ObservedSourceSHA256','HelperSHA256'});
    sidePath=fullfile(OutputRoot,'SciencePayload','PhaseC_SideMetrics_Actual_v1.csv');
    writetable(sideTable,sidePath,'Encoding','UTF-8');
    sideIntegrity=struct('IntegrityVersion','G4_SEED1_PHASE_C_SIDE_ROUTE_v1', ...
        'MetricCount',4,'MetricRosterExact',isequal(sideNames,["abs(A_E)";"D_pm";"signed A_E";"C_pm"]), ...
        'AllNativeValuesFinite',all(isfinite(sideValues)),'SideScalarRmodelCalled',false, ...
        'TotalDnumUsedForSideMetrics',false,'StochasticSideDistinguishabilityClassificationPerformed',false, ...
        'SciencePayloadObject',fileRecordLocal('SideMetrics',sidePath), ...
        'Evidence12','ACTUAL_PASS_CANDIDATE','PASS',all(isfinite(sideValues)),'CreatedUTC',utcLocal());
    assert(sideIntegrity.PASS,'G4PhaseC:SideMetricFinite','Side structural metric is nonfinite.');
    writeJsonLocal(fullfile(OutputRoot,'SideIntegrity','PhaseC_SideIntegrity_v1.json'),sideIntegrity);

    % C6/C7/C8: normalize each 6000-vector, then difference; exact zero is legal.
    blockSamples=round(0.010*fs);
    expectedCount=6000;
    assert(fs==256000,'G4PhaseC:EnvelopeGridFs','Formal envelope grid requires Fs=256000 Hz.');
    assert(blockSamples==2560,'G4PhaseC:EnvelopeGridStepSamples','Formal envelope grid step must be 2560 samples.');
    expectedTime=((0:expectedCount-1)'+0.5)*blockSamples/fs;
    m0cVsM2=isequal(double(envelopeM0C.TimeS),double(envelopeM2.TimeS));
    m0cVsCanonical=isequal(double(envelopeM0C.TimeS),expectedTime);
    m2VsCanonical=isequal(double(envelopeM2.TimeS),expectedTime);
    assert(height(envelopeM0C)==expectedCount&&height(envelopeM2)==expectedCount&& ...
        m0cVsM2&&m0cVsCanonical&&m2VsCanonical, ...
        'G4PhaseC:EnvelopeGrid','Frozen 6000-point envelope grid mismatch.');
    gridAudit=struct('AuditVersion','G4_SEED1_PHASE_C_CANONICAL_ENVELOPE_GRID_v1', ...
        'ScientificRunId',A.ScientificRunId,'PhaseCExecutionId',A.PhaseCExecutionId, ...
        'FrozenMetricHelperPath',A.HelperPath.ComputePaperResponseMetrics20ms_v2, ...
        'FrozenMetricHelperSHA256',A.HelperSHA.ComputePaperResponseMetrics20ms_v2, ...
        'RunnerPath',char(which(mfilename)),'RunnerSHA256',char(hashLocal(which(mfilename))), ...
        'OldGridConstruction','(0.005:0.01:59.995)''', ...
        'CanonicalGridConstruction','((0:expectedCount-1)''+0.5)*round(0.010*fs)/fs', ...
        'EnvelopeM0CCount',height(envelopeM0C),'EnvelopeM2Count',height(envelopeM2), ...
        'M0C_vs_M2_TimeS_BitwiseEqual',m0cVsM2, ...
        'M0C_vs_Canonical_TimeS_BitwiseEqual',m0cVsCanonical, ...
        'M2_vs_Canonical_TimeS_BitwiseEqual',m2VsCanonical, ...
        'GridStartS',expectedTime(1),'GridEndS',expectedTime(end), ...
        'GridStepSamples',blockSamples,'GridStepS',blockSamples/fs, ...
        'NewToleranceIntroduced',false,'FullVectorBitwiseGateRetained',true, ...
        'PASS',true,'CreatedUTC',utcLocal());
    writeJsonLocal(fullfile(OutputRoot,'EnvelopeVectorIntegrity','PhaseC_CanonicalEnvelopeGridAudit_v1.json'),gridAudit);
    modelVector=BuildG4ModelVectorProspective_v1(double(envelopeM0C.RMSAmplitude(:)), ...
        double(envelopeM2.RMSAmplitude(:)),"NORMALIZE_EACH_THEN_DIFFERENCE");
    if modelVector.Magnitude==0,zvdg="DIRECTION_UNDEFINED_ZERO_VECTOR";else,zvdg="NOT_TRIGGERED_VALID_NONZERO_VECTOR";end
    timeS=expectedTime;ehat_M0C=modelVector.NormalizedM0C;ehat_M2=modelVector.NormalizedM2; %#ok<NASGU>
    envelopePath=fullfile(OutputRoot,'SciencePayload','PhaseC_NormalizedEnvelopeVectors_v1.mat');
    save(envelopePath,'timeS','ehat_M0C','ehat_M2','-v7');
    v_model=modelVector.v_model;modelMagnitude=modelVector.Magnitude;directionState=zvdg; %#ok<NASGU>
    vectorPath=fullfile(OutputRoot,'SciencePayload','PhaseC_v_model_v1.mat');
    save(vectorPath,'timeS','v_model','modelMagnitude','directionState','-v7');

    % C9: frozen controls, production thin QR, continuous geometry only.
    controls=LoadG4FrozenControlVectors_v1(A.ControlVectorSources);
    projection=ProjectG4NumericalSubspaceThinQR_v1(controls.V,v_model);
    geometry=ComputeG4ContinuousVectorGeometry_v1(v_model,controls.V,controls.iC5);
    v_parallel=projection.Parallel;v_perp=projection.Perpendicular; %#ok<NASGU>
    numericalSubspaceFraction=NaN;orthogonalFraction=NaN;
    if modelMagnitude>0
        numericalSubspaceFraction=(norm(v_parallel)/modelMagnitude)^2;
        orthogonalFraction=(norm(v_perp)/modelMagnitude)^2;
    end
    qrPath=fullfile(OutputRoot,'SciencePayload','PhaseC_QR_MIDD_Actual_v1.mat');
    save(qrPath,'v_parallel','v_perp','projection','geometry','numericalSubspaceFraction','orthogonalFraction','-v7');
    vectorIntegrity=struct('IntegrityVersion','G4_SEED1_PHASE_C_ENVELOPE_VECTOR_v1', ...
        'EnvelopeLengthM0C',numel(ehat_M0C),'EnvelopeLengthM2',numel(ehat_M2), ...
        'TimeGridStartS',timeS(1),'TimeGridStepS',timeS(2)-timeS(1),'TimeGridEndS',timeS(end), ...
        'NormalizeEachFirst',true,'DifferenceSecond',true,'DifferenceThenNormalize',false, ...
        'ZVDGState',zvdg,'NoEpsilonDirection',true, ...
        'EnvelopeObject',fileRecordLocal('NormalizedEnvelopeVectors',envelopePath), ...
        'ModelVectorObject',fileRecordLocal('v_model',vectorPath), ...
        'Evidence13','ACTUAL_PASS_CANDIDATE','Evidence14','ACTUAL_PASS_CANDIDATE', ...
        'Evidence15','ACTUAL_ADJUDICATED_LEGAL_STATE','PASS',true,'CreatedUTC',utcLocal());
    writeJsonLocal(fullfile(OutputRoot,'EnvelopeVectorIntegrity','PhaseC_EnvelopeVectorIntegrity_v1.json'),vectorIntegrity);
    qrIntegrity=struct('IntegrityVersion','G4_SEED1_PHASE_C_THIN_QR_v1', ...
        'ProductionProjector','THIN_QR','RankQR',projection.RankQR, ...
        'QOrthogonalityResidual',projection.QOrthogonalityResidual, ...
        'ProjectionClosureResidual',projection.ClosureResidual,'ExpectedRank',4, ...
        'SVDProductionUse',false,'NormalMatrixInverseUse',false, ...
        'BinaryDirectionThreshold','PROHIBITED','MIDDIdentity','SECONDARY_CONTINUOUS_DIAGNOSTIC', ...
        'SciencePayloadObject',fileRecordLocal('QR_MIDD',qrPath), ...
        'Evidence16','ACTUAL_PASS_CANDIDATE','PASS',projection.RankQR==4&&projection.ClosureResidual<=4e-14, ...
        'CreatedUTC',utcLocal());
    assert(qrIntegrity.PASS,'G4PhaseC:QRClosure','Thin-QR projection closure failed.');
    writeJsonLocal(fullfile(OutputRoot,'QRIntegrity','PhaseC_QRIntegrity_v1.json'),qrIntegrity);

    % C10: external-reference records and pre-POST internally derived gate journal.
    eventReference=externalReferenceLocal('RawEventFacts',A.RawEventFactsReference,A);
    rawReference=externalReferenceLocal('RawM2SideResponses',A.RawM2SideResponses,A);
    m0cReference=externalReferenceLocal('M0CRawResponse',A.M0CRawResponse,A);
    eventRefPath=fullfile(OutputRoot,'Retention','EventFactsExternalAuthorityReference_v1.json');
    rawRefPath=fullfile(OutputRoot,'Retention','RawM2SideResponsesExternalAuthorityReference_v1.json');
    m0cRefPath=fullfile(OutputRoot,'Retention','M0CRawResponseExternalAuthorityReference_v1.json');
    writeJsonLocal(eventRefPath,eventReference);writeJsonLocal(rawRefPath,rawReference);writeJsonLocal(m0cRefPath,m0cReference);
    preGate=struct('GateJournalVersion','G4_SEED1_PHASE_C_PRE_POST_GATE_JOURNAL_v1', ...
        'ScientificRunId',A.ScientificRunId,'PhaseCExecutionId',A.PhaseCExecutionId, ...
        'Evidence8ObservedClosurePASS',observedClosure.PASS,'Evidence10NativeAndDnumPASS',metricReport.AllPass, ...
        'Evidence11D1MCTLegalityPASS',d1Integrity.PASS,'Evidence12SideRoutePASS',sideIntegrity.PASS, ...
        'Evidence13EnvelopePASS',true,'Evidence14ModelVectorPASS',true,'Evidence15ZVDGState',zvdg, ...
        'Evidence16ThinQRPASS',qrIntegrity.PASS,'GeneratedInternallyFromActualObjects',true, ...
        'CallerSuppliedGateBooleans',false,'DSAL','GENERATED_UNACCEPTED','G4_RESULT_COUNT',0, ...
        'TraversalCountThisTask',0,'RandomDrawCountThisTask',0,'EventRegenerationCountThisTask',0, ...
        'ImpulseResponseCallCount',0,'CreatedUTC',utcLocal());
    preGatePath=fullfile(OutputRoot,'GateEvidence','PhaseC_InternalGateJournal_PrePOST_v1.json');
    writeJsonLocal(preGatePath,preGate);

    retention=retentionTableLocal(A,AuthorizationArtifactPath,eventRefPath,rawRefPath,m0cRefPath, ...
        observedPath,nativePath,sidePath,envelopePath,vectorPath,preGatePath, ...
        fullfile(OutputRoot,'RuntimeAuthority','PhaseC_v1_2_PRE_RARC.json'));
    retentionReport=ValidateG4Seed1RetentionManifest_v1(retention,runIdentityLocal(A));
    assert(retentionReport.AllPass&&retentionReport.RequiredClassCount==12, ...
        'G4PhaseC:Retention','Frozen 12-class retention validation failed.');
    retentionCsv=fullfile(OutputRoot,'Retention','PhaseC_RetentionManifest_v1.csv');
    retentionJson=fullfile(OutputRoot,'Retention','PhaseC_RetentionManifest_v1.json');
    writetable(retention,retentionCsv,'Encoding','UTF-8');
    writeJsonLocal(retentionJson,struct('ManifestVersion','G4_SEED1_PHASE_C_RETENTION_v1', ...
        'Rows',{table2struct(retention)},'Validation',retentionReport,'PASS',true,'CreatedUTC',utcLocal()));
    writeJsonLocal(fullfile(OutputRoot,'Retention','PhaseC_RetentionIntegrity_v1.json'), ...
        struct('RequiredClassCount',12,'ObservedClassCount',height(retention), ...
        'ExternalAuthorityReferenceModeUsed',true,'NoRawEventFactsRead',true, ...
        'NoDuplicateGiantAuthorityCopied',true,'Evidence17','ACTUAL_PASS_CANDIDATE', ...
        'PASS',true,'CreatedUTC',utcLocal()));

    % Final POST-RARC and exact PRE/POST comparison.
    post=rarcLocal(A,"PHASE_C_POST");
    writeRarcLocal(post,fullfile(OutputRoot,'PostRARC','PhaseC_v1_2_POST_RARC.json'), ...
        fullfile(OutputRoot,'PostRARC','PhaseC_v1_2_POST_RARC.csv'));
    comparison=CompareG4PrePostRARC_v1(pre,post);
    assert(comparison.PASS,'G4PhaseC:PostRARC','Phase-C PRE/POST active scientific identity drifted.');
    writeJsonLocal(fullfile(OutputRoot,'PostRARC','PhaseC_v1_2_PRE_POST_RARC_Comparison.json'),comparison);

    % Frozen v3 RGEB: derive fail-closed pairing evidence from immutable actual artifacts.
    pairingForensics=jsondecode(fileread(string(A.PairingForensics.Path)));
    pairingVerdict=jsondecode(fileread(string(A.PairingVerdict.Path)));
    terminalReceipt=jsondecode(fileread(string(A.TerminalRecoveryReceipt.Path)));
    actualForensicsSHA=hashLocal(string(A.PairingForensics.Path));
    actualVerdictSHA=hashLocal(string(A.PairingVerdict.Path));
    pairAdapter=DeriveG4ActualPairingEvidenceAdapter_v1(pairingForensics,pairingVerdict, ...
        actualForensicsSHA,actualVerdictSHA,string(A.ScientificRunId), ...
        string(A.RecoveryExecutionId),string(A.RecoveryAuthorizationId), ...
        string(A.SourceEventFactsSHA256),string(A.PairingForensics.SHA256), ...
        string(A.PairingVerdict.SHA256));
    pairAdapter.PairingForensicsPath=A.PairingForensics.Path;
    pairAdapter.PairingForensicsBytes=double(A.PairingForensics.Bytes);
