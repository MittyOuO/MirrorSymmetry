function out=stackLocal(ME)
out=repmat(struct('File','','Name','','Line',0),numel(ME.stack),1);
for k=1:numel(ME.stack),out(k)=struct('File',ME.stack(k).file,'Name',ME.stack(k).name,'Line',ME.stack(k).line);end
end

function status=classifyFailureLocal(id)
if contains(id,'Authorization')||contains(id,'Entry')||contains(id,'PreRARC')||contains(id,'RuntimeRegistry')||contains(id,'Storage')
    status='HOLD_PHASE_C_ENTRY_AUTHORITY_FAILURE';
elseif contains(id,'ObservedResponseClosure')||contains(id,'NativeMetric')||contains(id,'Dnum')||contains(id,'QRClosure')||contains(id,'Retention')||contains(id,'RealGate')
    status='PHASE_C_QUARANTINED_HOLD';
else,status='HOLD_PHASE_C_UNRESOLVED';end
end

