function [Summary,Rows] = AuditProductionBottomGrid(InputParams,consumerProfile)
%AuditProductionBottomGrid Audit the exact common grid used by production.

if nargin<2||isempty(consumerProfile),consumerProfile='single';end
if isfield(InputParams,'DomainResolved') && isstruct(InputParams.DomainResolved)
    D=InputParams.DomainResolved;
else
    [~,D]=ResolveG3Parameters(InputParams,consumerProfile);
end
[xValues,xWidths,xAudit]=BuildBottomXValues(D.XmaxM,InputParams.RecvRange, ...
    D.GridI,D.GridIPlusM,D.BoundaryPolicy);
Rows=cell(numel(xValues),1);
candidate=0; axisCount=0; plusCount=0; minusCount=0;
totalArea=0; plusArea=0; minusArea=0; minY=inf; maxY=-inf;
maxSource=0; maxReceiver=0; cutoffRows=0; cutoffExcluded=0;
firstX=NaN; firstY=NaN;
for k=1:numel(xValues)
    [row,a]=BuildBottomGridRow(xValues(k),xWidths(k),D.YmaxM, ...
        InputParams.RecvRange,D.GridI,D.GridIPlusM, ...
        D.TotalTwoLegHorizontalRangeLimitM,D.BoundaryPolicy);
    Rows{k}=row;
    candidate=candidate+a.CandidateCellCount; axisCount=axisCount+a.AxisFacetCount;
    plusCount=plusCount+a.PlusCount; minusCount=minusCount+a.MinusCount;
    totalArea=totalArea+a.TotalArea; plusArea=plusArea+a.PlusArea; minusArea=minusArea+a.MinusArea;
    minY=min(minY,a.ActualMinY); maxY=max(maxY,a.ActualMaxY);
    maxSource=max(maxSource,a.ActualMaxSourceRadialRange);
    maxReceiver=max(maxReceiver,a.ActualMaxReceiverRadialRange);
    if a.CutoffTriggered
        cutoffRows=cutoffRows+1; cutoffExcluded=cutoffExcluded+a.CutoffExcludedCandidateCellCount;
        if isnan(firstX), firstX=xValues(k); firstY=a.FirstCutoffYAbs; end
    end
end
overshoot=max([xAudit.BoundaryOvershootM,0,-D.YmaxM-minY,maxY-D.YmaxM]);
Summary=table(string(D.BoundaryPolicy),D.RmaxM,D.XmaxM,D.YmaxM, ...
    min(xValues),max(xValues),minY,maxY,overshoot,D.SourceToBottomRangeMaxM, ...
    D.BottomToReceiverRangeMaxM,maxSource,maxReceiver,candidate,totalArea, ...
    plusCount,minusCount,plusArea,minusArea,axisCount,numel(xValues), ...
    cutoffRows>0,cutoffRows,cutoffExcluded,firstX,firstY, ...
    D.TotalTwoLegHorizontalRangeLimitM, ...
    'VariableNames',{'BoundaryPolicy','RequestedRmaxM','ConfiguredXmaxM','ConfiguredYmaxM', ...
    'ActualMinX','ActualMaxX','ActualMinY','ActualMaxY','BoundaryOvershoot', ...
    'DerivedSourceToBottomRangeMaxM','DerivedBottomToReceiverRangeMaxM', ...
    'ActualMaxSourceRadialRange','ActualMaxReceiverRadialRange', ...
    'TotalCandidateCellCount','TotalCandidateArea','PlusCount','MinusCount', ...
    'PlusArea','MinusArea','AxisFacetCount','XCount','CutoffTriggered', ...
    'CutoffRowCount','CutoffExcludedCandidateCellCount','FirstCutoffX', ...
    'FirstCutoffYAbs','TotalTwoLegHorizontalRangeLimitM'});
end
