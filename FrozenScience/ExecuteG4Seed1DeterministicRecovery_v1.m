    releaseReceipt=struct('ReceiptVersion','G4_SEED1_RECOVERY_LOCK_RELEASE_v1','RecoveryLockPath',auth.RecoveryLockPath, ...
        'RecoveryLockExistsAfterRelease',isfile(auth.RecoveryLockPath),'TerminalReceiptSHA256',char(terminalReceiptSHA), ...
        'RECOVERY_SEALEDJournalPath',sealedJournalPath,'RECOVERY_SEALEDJournalSHA256',char(journalPrevious), ...
        'ReleasedUTC',utcLocal(),'PASS',~isfile(auth.RecoveryLockPath));
    writeJsonLocal(fullfile(OutputRoot,'RecoveryLockReleaseReceipt.json'),releaseReceipt,false);
    Result=terminalReceipt;Result.RecoveryLockReleased=releaseReceipt.PASS;Result.FinalJournalSHA256=char(journalPrevious);
    writeJsonLocal(fullfile(OutputRoot,'RecoveryRunnerResult.json'),Result,false);
    fprintf('%s\n',terminal);
catch ME
    failureTerminal=classifyFailureLocal(ME,entered);
    failure=struct('FailureVersion','G4_SEED1_ACTUAL_RECOVERY_FAILURE_v1','TerminalBranch',char(failureTerminal), ...
        'CurrentStage',char(currentStage),'RecoveryEntered',entered,'AuthorizationConsumed',entered, ...
        'Identifier',ME.identifier,'Message',ME.message,'Stack',ME.stack,'UTC',utcLocal(), ...
        'M2TraversalCountDuringRecovery',0,'RandomDrawCountDuringRecovery',0);
    if isfolder(OutputRoot)
        if entered,failName="RecoveryUnresolvedReceipt.json";else,failName="RecoveryPreEntryFailureReceipt.json";end
        failPath=fullfile(OutputRoot,failName);
        try,writeJsonLocal(failPath,failure,false);catch,end
    end
    if lockAcquired&&isfield(lockToken,'Stream')
        try,lockToken.Stream.Dispose();catch,end
    end
    fprintf(2,'%s: %s\n',failureTerminal,ME.message);rethrow(ME);
end
end

