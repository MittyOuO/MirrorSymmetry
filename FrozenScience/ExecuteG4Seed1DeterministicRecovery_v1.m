function label=classifyFailureLocal(ME,entered)
if entered,label="HOLD_RECOVERY_UNRESOLVED";return,end
switch string(ME.identifier)
    case "G4Recovery:DCacheAuthorityMismatch",label="HOLD_D_CACHE_AUTHORITY_MISMATCH";
    case "G4Recovery:ScratchBelowFrozenGate",label="HOLD_RECOVERY_SCRATCH_SPACE_BELOW_FROZEN_GATE";
    case "G4Recovery:TemporaryProjectionExceedsFrozenGate",label="HOLD_RECOVERY_PROJECTED_TEMP_EXCEEDS_FROZEN_GATE";
    otherwise,label="HOLD_RECOVERY_PREENTRY_FAILURE";
end
end

function writeJsonLocal(path,value,allowOverwrite)
if ~allowOverwrite,assert(~isfile(path),'G4Recovery:ArtifactExists','Refusing to overwrite %s.',path);end
folder=fileparts(path);if ~isfolder(folder),mkdir(folder);end
tmp=string(path)+".pending";fid=fopen(tmp,'w','n','UTF-8');assert(fid>=0,'G4Recovery:Write','Cannot write %s.',tmp);c=onCleanup(@()fclose(fid));
fprintf(fid,'%s',jsonencode(value,'PrettyPrint',true));clear c
if isfile(path),delete(path);end;[ok,msg]=movefile(tmp,path,'f');assert(ok,'G4Recovery:Commit','Cannot commit %s: %s',path,msg);
end

function tf=pathEqualLocal(a,b)
tf=strcmpi(char(java.io.File(char(a)).getCanonicalPath()),char(java.io.File(char(b)).getCanonicalPath()));
end

function sha=hashLocal(path)
md=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(path,'r');assert(fid>=0,'G4Recovery:HashOpen','Cannot hash %s.',path);c=onCleanup(@()fclose(fid)); %#ok<NASGU>
while true,d=fread(fid,16*1024*1024,'*uint8');if isempty(d),break,end;md.update(typecast(d,'int8'));end
sha=string(lower(reshape(dec2hex(mod(double(md.digest()),256),2).',1,[])));
end

function text=utcLocal()
text=char(datetime('now','TimeZone','UTC','Format',"yyyy-MM-dd'T'HH:mm:ss.SSSXXX"));
end
