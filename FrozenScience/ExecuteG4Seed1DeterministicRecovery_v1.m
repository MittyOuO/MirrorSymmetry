function R=freshRarcLocal(registry,phase,outputRoot)
rows=table2struct(registry);audit=repmat(struct('Role','','Name','','ExpectedPath','','ExpectedBytes',0, ...
    'ExpectedSHA256','','ResolutionMode','','ResolvedPath','','ResolvedCount',0,'ActualBytes',0, ...
    'ActualSHA256','','PathPass',false,'BytesPass',false,'SHAPass',false,'ShadowPass',false,'Pass',false),numel(rows),1);
for k=1:numel(rows)
    expected=string(rows(k).ExpectedPath);mode=string(rows(k).ResolutionMode);resolved=expected;resolvedCount=1;shadowPass=true;
    if mode=="WHICH_EXACT"
        found=which(char(rows(k).Name),'-all');
        if ischar(found),allFound=string({found});else,allFound=string(found);end
        allFound=allFound(strlength(allFound)>0);resolvedCount=numel(allFound);shadowPass=resolvedCount==1;
        if isempty(allFound),resolved="";else,resolved=allFound(1);end
    end
    exists=isfile(resolved);actualBytes=0;actualSHA="";
    if exists,info=dir(resolved);actualBytes=info.bytes;actualSHA=hashLocal(resolved);end
    pathPass=pathEqualLocal(resolved,expected);bytesPass=exists&&actualBytes==double(rows(k).Bytes);shaPass=exists&&actualSHA==string(rows(k).SHA256);
    audit(k)=struct('Role',char(string(rows(k).Role)),'Name',char(string(rows(k).Name)), ...
        'ExpectedPath',char(expected),'ExpectedBytes',double(rows(k).Bytes),'ExpectedSHA256',char(string(rows(k).SHA256)), ...
        'ResolutionMode',char(mode),'ResolvedPath',char(resolved),'ResolvedCount',resolvedCount,'ActualBytes',actualBytes, ...
        'ActualSHA256',char(actualSHA),'PathPass',pathPass,'BytesPass',bytesPass,'SHAPass',shaPass, ...
        'ShadowPass',shadowPass,'Pass',pathPass&&bytesPass&&shaPass&&shadowPass);
end
T=struct2table(audit);csvPath=fullfile(outputRoot,phase+"_RARC.csv");writetable(T,csvPath);
R=struct('RARCVersion','G4_SEED1_RECOVERY_EXACT_RARC_v1','Phase',char(phase),'RowCount',numel(audit), ...
    'PassCount',nnz([audit.Pass]),'FailureCount',nnz(~[audit.Pass]),'Rows',audit,'CSVPath',char(csvPath), ...
    'CreatedUTC',utcLocal(),'PASS',all([audit.Pass]));
R.JSONPath=char(fullfile(outputRoot,phase+"_RARC.json"));writeJsonLocal(R.JSONPath,R,false);
end

